use std::path::Path;

use anyhow::Context;
use tracing::{info, instrument};

use crate::models::{directories::ProjectDirectory, language_config::SCLANG_CONF_FILE};

pub const GITIGNORE_FILE: &str = ".gitignore";

/// The files magnet generates within a project, anchored to the project root
fn generated_entries() -> Vec<String> {
    vec![
        format!("/{}/", String::from(ProjectDirectory::Dist)),
        format!("/{}/", String::from(ProjectDirectory::Packages)),
        format!("/{SCLANG_CONF_FILE}"),
    ]
}

/// `true` if `line` already ignores `entry`, e.g. `magnet_packages/` or `/magnet_packages` for `/magnet_packages/`
fn ignores(line: &str, entry: &str) -> bool {
    let normalize = |pattern: &str| pattern.trim().trim_matches('/').to_string();
    normalize(line) == normalize(entry)
}

fn read_gitignore(root: &Path) -> anyhow::Result<String> {
    let path = root.join(GITIGNORE_FILE);
    match path.exists() {
        true => std::fs::read_to_string(&path).with_context(|| format!("Could not read {path:?}")),
        false => Ok(String::new()),
    }
}

fn missing_entries(content: &str) -> Vec<String> {
    generated_entries()
        .into_iter()
        .filter(|entry| !content.lines().any(|line| ignores(line, entry)))
        .collect()
}

/// The entries [write_gitignore] would add to the `.gitignore` of `root`
pub fn missing_gitignore_entries(root: &Path) -> anyhow::Result<Vec<String>> {
    Ok(missing_entries(&read_gitignore(root)?))
}

/// Creates the `.gitignore` of a project, or appends the entries it lacks
#[instrument]
pub fn write_gitignore(root: &Path) -> anyhow::Result<()> {
    let path = root.join(GITIGNORE_FILE);
    let mut content = read_gitignore(root)?;
    let missing = missing_entries(&content);
    if missing.is_empty() {
        return Ok(());
    }

    if !content.is_empty() {
        if !content.ends_with('\n') {
            content.push('\n');
        }
        content.push('\n');
    }
    content.push_str("# generated by magnet\n");
    for entry in &missing {
        content.push_str(entry);
        content.push('\n');
    }
    std::fs::write(&path, content).with_context(|| format!("Could not write {path:?}"))?;
    info!("Added {} to {GITIGNORE_FILE}", missing.join(", "));
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    fn read(dir: &tempfile::TempDir) -> String {
        fs::read_to_string(dir.path().join(GITIGNORE_FILE)).unwrap()
    }

    #[test]
    fn test_new_gitignore() {
        let dir = tempfile::tempdir().unwrap();
        write_gitignore(dir.path()).unwrap();
        assert_eq!(
            read(&dir),
            "# generated by magnet\n/dist/\n/magnet_packages/\n/sclang_conf.yaml\n"
        );
    }

    #[test]
    fn test_existing_gitignore() {
        let dir = tempfile::tempdir().unwrap();
        // without a trailing newline, and with an entry in another notation
        fs::write(dir.path().join(GITIGNORE_FILE), "*.bak\nmagnet_packages").unwrap();
        write_gitignore(dir.path()).unwrap();
        assert_eq!(
            read(&dir),
            "*.bak\nmagnet_packages\n\n# generated by magnet\n/dist/\n/sclang_conf.yaml\n"
        );
    }

    #[test]
    fn test_unchanged_if_complete() {
        let dir = tempfile::tempdir().unwrap();
        write_gitignore(dir.path()).unwrap();
        let content = read(&dir);
        write_gitignore(dir.path()).unwrap();
        assert_eq!(read(&dir), content);
    }

    #[test]
    fn test_ignores() {
        for line in [
            "/magnet_packages/",
            "magnet_packages/",
            "/magnet_packages",
            "magnet_packages",
            "  magnet_packages/ ",
        ] {
            assert!(ignores(line, "/magnet_packages/"), "{line}");
        }
        for line in [
            "# magnet_packages/",
            "magnet_packages/quarks",
            "!magnet_packages/",
            "Classes/magnet_packages/",
        ] {
            assert!(!ignores(line, "/magnet_packages/"), "{line}");
        }
    }
}
