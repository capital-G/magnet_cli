//! The class which isolates the server's plugins, see DESIGN.md "Server plugins"

use std::path::Path;

use anyhow::Context;
use tracing::{instrument, trace};

use crate::target::{PluginApi, PLUGIN_APIS};

/// generated into `magnet_packages/`, which is on the include path of `sclang_conf.yaml`
pub const SERVER_OPTIONS_FILE: &str = "MagnetServerOptions.sc";

/// The folder within `magnet_packages/` with the binaries of a lepton developed in the project
pub const DEV_DIR: &str = ".dev";

/// The class which sets `ServerOptions.ugenPluginsPath` (`-U`) to SuperCollider's own `plugins`
/// folder and, of each package in `magnet_packages`, the folder `plugins/<platform>/<abi>` which
/// matches the server: this platform and the newest plugin API the server loads (the same
/// major, a minor up to its own), since scsynth loads every sub folder of a path. So globally
/// installed plugins are not loaded, and a project can hold the binaries of several platforms
/// and plugin APIs (DESIGN.md "Server plugins").
/// The paths are determined when sclang compiles the class, so the file holds no absolute
/// paths and fits the SuperCollider it runs in. The plugin API is `api` if given (`--abi`, e.g.
/// for an older scsynth or a development build), otherwise the one of the running
/// SuperCollider's version ([PLUGIN_APIS]). Since 3.15 has no `ServerOptions.defaultValues`
/// anymore, it becomes `Server.defaultOptionsClass` and sets the paths on the existing servers
/// (`upstream_plan.md` U11). With `dev`, `magnet_packages/.dev` gets loaded as well.
pub fn server_options_class(dev: bool, api: Option<PluginApi>) -> String {
    let packages = match dev {
        true => format!("(packages +/+ \"*/plugins\").pathMatch ++ (packages +/+ \"{DEV_DIR}/*/plugins\").pathMatch"),
        // `*` doesn't match hidden folders like `.dev`
        false => "(packages +/+ \"*/plugins\").pathMatch".to_string(),
    };
    let api = match api {
        Some(api) => format!("[{}, {}]", api.major, api.minor),
        None => "nil".to_string(),
    };
    let table: String = PLUGIN_APIS
        .iter()
        .map(|(major, first, last, api)| {
            format!(
                "\n\t\t\t{{ major == {major} and: {{ minor >= {first} and: {{ minor <= {last} }} }} }} {{ [{}, {}] }}",
                api.major, api.minor
            )
        })
        .collect();
    SERVER_OPTIONS_CLASS
        .replace("{packages}", &packages)
        .replace("{api}", &api)
        .replace("{table}", &table)
}

const SERVER_OPTIONS_CLASS: &str = r#"// generated by magnet, changes get overwritten
// Loads only the server plugins of SuperCollider and of this project's magnet_packages, not the
// globally installed ones: of each package the binaries of this platform and of the newest
// plugin API the server loads. Plugin paths which are set explicitly are kept.
MagnetServerOptions : ServerOptions {
	classvar <pluginPaths;

	*initClass {
		var packages = this.filenameSymbol.asString.dirname;
		var resources = Platform.resourceDir;
		var platform, api;
		Class.initClassTree(Server);
		pluginPaths = [
			// macOS and Windows
			resources +/+ "plugins",
			// Linux: <prefix>/share/SuperCollider -> <prefix>/lib{,64}/SuperCollider/plugins
			resources +/+ "../../lib/SuperCollider/plugins",
			resources +/+ "../../lib64/SuperCollider/plugins"
		].select { |path| File.exists(path) };
		if(pluginPaths.isEmpty) {
			"magnet: could not find the plugins folder of SuperCollider, so the server loads all installed plugins".warn;
			pluginPaths = nil;
			^this
		};
		platform = this.platformTag;
		// given via --abi when installing, otherwise the one of this SuperCollider
		api = {api} ?? { this.pluginApi };
		if(platform.isNil) {
			"magnet: % % is no platform of magnet, so the server loads no plugins of magnet_packages".format(thisProcess.platform.name, Platform.architecture).warn
		} {
			if(api.isNil) {
				"magnet: the plugin API of SuperCollider % is not known, so the newest binaries of each package get loaded. Set it via MAGNET_ABI when running magnet install".format(Main.version).warn
			};
			({packages}).do { |plugins|
				var folder = this.apiFolder(plugins +/+ platform, api);
				if(folder.notNil) { pluginPaths = pluginPaths.add(folder) }
			}
		};
		if(Server.defaultOptionsClass == ServerOptions) {
			Server.defaultOptionsClass = this
		};
		Server.all.do { |server|
			if(server.options.ugenPluginsPath.isNil) {
				server.options.ugenPluginsPath = pluginPaths
			}
		}
	}

	*new {
		^super.new.ugenPluginsPath_(pluginPaths)
	}

	// the platform tag of magnet, e.g. "macos_arm64"
	*platformTag {
		var os = (osx: "macos", linux: "linux", windows: "windows")[thisProcess.platform.name];
		var arch = (x86_64: "x86_64", AArch64: "arm64", AArch32: "armv7")[Platform.architecture];
		^if(os.notNil and: { arch.notNil }) { os ++ "_" ++ arch }
	}

	// the plugin API of this SuperCollider as [major, minor], nil if it's not known
	*pluginApi {
		var major = Main.scVersionMajor, minor = Main.scVersionMinor;
		^case{table}
	}

	// the folder `api<major>_<minor>` within `folder` with the major of `api` and the highest
	// minor up to the one of `api`, or without `api` the newest one; nil if there is none
	*apiFolder { |folder, api|
		var best, bestApi;
		(folder +/+ "*").pathMatch.do { |path|
			var name = path.withoutTrailingSlash.basename, numbers;
			if("^api[0-9]+_[0-9]+$".matchRegexp(name)) {
				numbers = name.drop(3).split($_).collect(_.asInteger);
				if(api.isNil or: { numbers[0] == api[0] and: { numbers[1] <= api[1] } }) {
					if(bestApi.isNil or: { numbers[0] > bestApi[0] or: { numbers[0] == bestApi[0] and: { numbers[1] > bestApi[1] } } }) {
						best = path;
						bestApi = numbers
					}
				}
			}
		};
		^best
	}
}
"#;

#[instrument]
pub fn write_server_options(
    packages_dir: &Path,
    dev: bool,
    api: Option<PluginApi>,
) -> anyhow::Result<()> {
    std::fs::create_dir_all(packages_dir)
        .with_context(|| format!("Could not create {packages_dir:?}"))?;
    let path = packages_dir.join(SERVER_OPTIONS_FILE);
    std::fs::write(&path, server_options_class(dev, api))
        .with_context(|| format!("Could not write {path:?}"))?;
    trace!(?path, "Written server options");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_server_options_class() {
        let class = server_options_class(false, None);
        assert!(class.contains("MagnetServerOptions : ServerOptions {"));
        assert!(class.contains("(packages +/+ \"*/plugins\").pathMatch).do"));
        assert!(!class.contains(".dev"));
        // the plugin API of this SuperCollider, from the same table as magnet's
        assert!(class.contains("api = nil ?? { this.pluginApi };"));
        assert!(
            class.contains("{ major == 3 and: { minor >= 9 and: { minor <= 14 } } } { [3, 0] }")
        );
        // no absolute paths, the class finds them itself, and no placeholders are left
        assert!(!class.contains("\"/"));
        for placeholder in ["{packages}", "{api}", "{table}"] {
            assert!(!class.contains(placeholder), "{placeholder}");
        }

        // an abi given via --abi wins, e.g. for an older scsynth
        let class = server_options_class(true, Some(PluginApi::new(4, 1)));
        assert!(class.contains("api = [4, 1] ?? { this.pluginApi };"));
        assert!(class.contains(
            "((packages +/+ \"*/plugins\").pathMatch ++ (packages +/+ \".dev/*/plugins\").pathMatch).do"
        ));
    }

    #[test]
    fn test_write_server_options() {
        let dir = tempfile::tempdir().unwrap();
        let packages = dir.path().join("magnet_packages");
        write_server_options(&packages, true, None).unwrap();
        assert_eq!(
            std::fs::read_to_string(packages.join(SERVER_OPTIONS_FILE)).unwrap(),
            server_options_class(true, None)
        );
    }
}
