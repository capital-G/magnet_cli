use std::path::{Path, PathBuf};

use anyhow::Context;
use tracing::{instrument, trace};

use crate::{
    config::constants::MAGNET_PROJECT_FILE,
    models::{
        directories::ProjectDirectory,
        project_manifest::{MagnetManifestV1, MagnetManifestV1DependenciesValue, ProjectManifest},
    },
    sclang::{Sclang, MAGNET_SCLANG_ENV},
};

/// sclang language config in the root of the project, see DESIGN.md
pub const SCLANG_CONF_FILE: &str = "sclang_conf.yaml";

/// characters which start a wildcard within a glob
const WILDCARDS: [char; 4] = ['*', '?', '[', '{'];

/// The directory a glob starts in, i.e. the path up to its first wildcard component,
/// e.g. `Classes/**.sc` → `<root>/Classes` and `*.sc` → `<root>`.
/// A glob without wildcards stands for itself if it is a directory, otherwise for its parent.
pub fn glob_base_dir(root: &Path, glob: &str) -> PathBuf {
    let mut base = root.to_path_buf();
    let mut has_wildcard = false;
    for component in glob
        .split(['/', '\\'])
        .filter(|component| !component.is_empty() && *component != ".")
    {
        if component.contains(WILDCARDS) {
            has_wildcard = true;
            break;
        }
        base.push(component);
    }
    if !has_wildcard && !base.is_dir() && base != root {
        base.pop();
    }
    base
}

/// The `includePaths` of sclang for a project.
/// With a known sclang, the default paths get excluded and its class library gets included
/// explicitly, since `excludeDefaultPaths: true` also excludes the class library. So globally
/// installed extensions are not compiled. Without sclang, the default paths stay enabled.
/// The paths are absolute, because sclang resolves relative paths against its working
/// directory, which is not the project root when started via the IDE.
#[derive(Debug, PartialEq)]
pub struct LanguageConfig {
    pub sclang: Option<Sclang>,
    pub include_paths: Vec<PathBuf>,
}

impl LanguageConfig {
    /// Includes the base directories of the global paths of the project, `external`,
    /// and the base directories of the global paths of its `path` dependencies.
    /// All paths are absolute and exact duplicates are dropped.
    /// Overlapping directories are fine, since sclang compiles a directory only once.
    pub fn for_project(
        root: &Path,
        manifest: &MagnetManifestV1,
        sclang: Option<Sclang>,
    ) -> anyhow::Result<Self> {
        let root = std::path::absolute(root)
            .with_context(|| format!("Could not obtain the absolute path of {root:?}"))?;

        let mut include_paths = source_dirs(&root, manifest);
        include_paths.push(root.join(String::from(ProjectDirectory::External)));

        let mut path_dependencies: Vec<(&String, &String)> = manifest
            .dependencies
            .iter()
            .filter_map(|(name, dependency)| match dependency {
                MagnetManifestV1DependenciesValue::Object {
                    path: Some(path), ..
                } => Some((name, path)),
                _ => None,
            })
            .collect();
        // the order of a HashMap is random, but the file should be stable
        path_dependencies.sort();
        for (name, path) in path_dependencies {
            let dependency_root = root.join(path);
            let manifest_path = dependency_root.join(MAGNET_PROJECT_FILE);
            if manifest_path.is_file() {
                let dependency_manifest = ProjectManifest::open(manifest_path)
                    .with_context(|| format!("Could not open the manifest of {name}"))?;
                include_paths.extend(source_dirs(
                    &dependency_root,
                    dependency_manifest.get_manifest(),
                ));
            } else {
                // e.g. a legacy quark, which is used as a whole
                include_paths.push(dependency_root);
            }
        }

        let mut unique_paths = vec![];
        for path in include_paths {
            if !unique_paths.contains(&path) {
                unique_paths.push(path);
            }
        }
        Ok(Self {
            sclang,
            include_paths: unique_paths,
        })
    }

    pub fn to_yaml(&self) -> String {
        let mut yaml = format!(
            "# generated by magnet, changes get overwritten - edit {MAGNET_PROJECT_FILE} instead\n"
        );
        let include_paths = match &self.sclang {
            Some(sclang) => {
                yaml.push_str(&format!(
                    "# for {}, set {MAGNET_SCLANG_ENV} to use another sclang\n\
                     excludeDefaultPaths: true\n",
                    sclang.binary.display()
                ));
                [
                    vec![sclang.class_library.clone()],
                    self.include_paths.clone(),
                ]
                .concat()
            }
            None => {
                yaml.push_str(&format!(
                    "# sclang was not found, so globally installed extensions are not excluded.\n\
                     # Set {MAGNET_SCLANG_ENV} and run magnet install again to change this.\n\
                     excludeDefaultPaths: false\n"
                ));
                self.include_paths.clone()
            }
        };
        yaml.push_str(&format!("\nincludePaths:\n{}", yaml_list(&include_paths)));
        yaml
    }

    #[instrument(skip(self))]
    pub fn write(&self, root: &Path) -> anyhow::Result<()> {
        let path = root.join(SCLANG_CONF_FILE);
        std::fs::write(&path, self.to_yaml())
            .with_context(|| format!("Could not write {path:?}"))?;
        trace!(?path, "Written language config");
        Ok(())
    }
}

fn yaml_list(paths: &[PathBuf]) -> String {
    paths
        .iter()
        // single quoted YAML strings take backslashes literally, only `'` needs escaping
        .map(|path| format!("  - '{}'\n", path.to_string_lossy().replace('\'', "''")))
        .collect()
}

/// base directories of the global paths of a project, `classes` if it declares none
fn source_dirs(root: &Path, manifest: &MagnetManifestV1) -> Vec<PathBuf> {
    match &manifest.artifact {
        Some(artifact) if !artifact.global_paths.is_empty() => artifact
            .global_paths
            .iter()
            .map(|glob| glob_base_dir(root, glob))
            .collect(),
        _ => vec![root.join(String::from(ProjectDirectory::Classes))],
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    fn manifest(extra: &str) -> MagnetManifestV1 {
        toml::from_str(&format!(
            "magnet-version = 1\n\
             \n\
             [package]\n\
             name = \"foo\"\n\
             version = \"0.1.0\"\n\
             kind = \"quark\"\n\
             {extra}"
        ))
        .unwrap()
    }

    #[test]
    fn test_glob_base_dir() {
        let root = tempfile::tempdir().unwrap();
        let root = root.path();
        fs::create_dir_all(root.join("HelpSource")).unwrap();

        for (glob, expected) in [
            ("Classes/**.sc", root.join("Classes")),
            ("Classes/**/*.sc", root.join("Classes")),
            ("./Classes/*.sc", root.join("Classes")),
            ("src/{a,b}/*.sc", root.join("src")),
            ("lib/Foo?.sc", root.join("lib")),
            ("*.sc", root.to_path_buf()),
            ("**/*.sc", root.to_path_buf()),
            // without wildcards: a directory stands for itself, a file for its parent
            ("HelpSource", root.join("HelpSource")),
            ("Classes/Foo.sc", root.join("Classes")),
            ("Foo.sc", root.to_path_buf()),
        ] {
            assert_eq!(glob_base_dir(root, glob), expected, "{glob}");
        }
    }

    #[test]
    fn test_default_include_paths() {
        let root = tempfile::tempdir().unwrap();
        let config = LanguageConfig::for_project(root.path(), &manifest(""), None).unwrap();
        assert_eq!(
            config.include_paths,
            [root.path().join("classes"), root.path().join("external")]
        );
    }

    #[test]
    fn test_include_paths_of_global_paths() {
        let root = tempfile::tempdir().unwrap();
        let manifest = manifest(
            "\n[artifact]\nglobal-paths = [\"*.sc\", \"Classes/**.sc\", \"Classes/*.schelp\"]\n",
        );
        let config = LanguageConfig::for_project(root.path(), &manifest, None).unwrap();
        // a converted legacy quark with root-level classes, without duplicates
        assert_eq!(
            config.include_paths,
            [
                root.path().to_path_buf(),
                root.path().join("Classes"),
                root.path().join("external")
            ]
        );
    }

    #[test]
    fn test_include_paths_of_path_dependencies() {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path().join("project");
        fs::create_dir_all(&root).unwrap();
        // a magnet project, using the base directories of its global paths
        let bar = dir.path().join("bar");
        fs::create_dir_all(&bar).unwrap();
        fs::write(
            bar.join(MAGNET_PROJECT_FILE),
            "magnet-version = 1\n\n[package]\nname = \"bar\"\nversion = \"0.1.0\"\nkind = \"quark\"\n\n[artifact]\nglobal-paths = [\"lib/**.sc\"]\n",
        )
        .unwrap();
        // a legacy quark without manifest is used as a whole
        let baz = dir.path().join("baz");
        fs::create_dir_all(&baz).unwrap();

        let manifest = manifest(
            "\n[dependencies]\nbaz = { path = \"../baz\" }\nbar = { path = \"../bar\" }\nqux = \"^1.0\"\n",
        );
        let config = LanguageConfig::for_project(&root, &manifest, None).unwrap();
        assert_eq!(
            config.include_paths,
            [
                root.join("classes"),
                root.join("external"),
                root.join("../bar").join("lib"),
                root.join("../baz"),
            ]
        );
    }

    #[test]
    fn test_relative_root_becomes_absolute() {
        let config = LanguageConfig::for_project(Path::new("foo"), &manifest(""), None).unwrap();
        assert!(config.include_paths.iter().all(|path| path.is_absolute()));
    }

    #[test]
    fn test_to_yaml() {
        let mut config = LanguageConfig {
            sclang: None,
            include_paths: vec![
                PathBuf::from("/home/me/my project/classes"),
                PathBuf::from("/home/me/it's/external"),
            ],
        };
        assert_eq!(
            config.to_yaml(),
            "# generated by magnet, changes get overwritten - edit magnet.toml instead\n\
             # sclang was not found, so globally installed extensions are not excluded.\n\
             # Set MAGNET_SCLANG and run magnet install again to change this.\n\
             excludeDefaultPaths: false\n\
             \n\
             includePaths:\n  \
             - '/home/me/my project/classes'\n  \
             - '/home/me/it''s/external'\n"
        );

        config.sclang = Some(Sclang {
            binary: PathBuf::from("/opt/sc/bin/sclang"),
            class_library: PathBuf::from("/opt/sc/share/SuperCollider/SCClassLibrary"),
        });
        assert_eq!(
            config.to_yaml(),
            "# generated by magnet, changes get overwritten - edit magnet.toml instead\n\
             # for /opt/sc/bin/sclang, set MAGNET_SCLANG to use another sclang\n\
             excludeDefaultPaths: true\n\
             \n\
             includePaths:\n  \
             - '/opt/sc/share/SuperCollider/SCClassLibrary'\n  \
             - '/home/me/my project/classes'\n  \
             - '/home/me/it''s/external'\n"
        );
    }
}
